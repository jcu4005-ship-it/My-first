-- 자동 테스트가 만든 호스트를 공개 목록에서 숨기기 (대표 요청 2026-11-14)
--  - is_test = true 인 호스트와 그 프로그램·글은 메인·목록·검색에 나오지 않음
--  - 계정·신청·결제·감사 기록은 그대로 남김 (삭제하지 않음). 주소로 직접 들어가면 볼 수 있음
--  - 이 값은 앱(회원·관리자 화면)에서 바꿀 수 없음. 스테이징 배포 단계의 SQL로만 표시
-- ============================================================================

alter table public.host_profiles add column is_test boolean not null default false;

-- 목록에서 걸러내기 위해 읽기만 허용 (쓰기 권한은 주지 않음)
grant select (is_test) on public.host_profiles to anon, authenticated;
